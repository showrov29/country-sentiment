// Simple spam filter
function isSpam(commentText) {
  if (!commentText) return true;
  const urlPattern = /(https?:\/\/[^\s]+)/g;
  const repeatedChars = /(.)\1{5,}/;
  return urlPattern.test(commentText) || repeatedChars.test(commentText);
}

